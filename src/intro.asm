; =============================================================================
; intro.prg - a short intro: the Codeurs en Seine logo waves
;
; For Codeurs en Seine 2026 (Rouen, Kindarena, 19.11.2026).
;   always   top border : stable raster copper bars         (irq_bars1/irq_bars2)
;            row 23     : title                             (text, ROM font)
;            row 24     : "wave, codeurs!" smooth scroller   (irq_split/irq_bottom)
;   logo     18x8 cells : 2x2 chase, a diagonal wave travels through the logo:
;                        each cell slides down out of the logo, clears, slides
;                        back in from above, then settles for half a second.
;            only the cells whose wave edge moves are redrawn (a dozen per frame).
;
; Data (charset, cells, wave table) is generated by tools/ces_intro.py from
; assets/codeurs-en-seine-logo.svg into src/gfx/ces_intro.*
;
; Build:  make intro       -> build/intro.prg      (standalone, no music)
;         make run-intro   -> launch in VICE
; Memory: code $0801-$0fff (guard below), charset $2000, data from $3000.
; =============================================================================
!source "c64.asm"
!source "src/gfx/ces_intro.inc.asm"     ; generated: CELLS_W/H, CELL_COUNT, CES_CHARS, CES_FIRST, HIDDEN

CODE_END     = $1000            ; code must stay below
CHARSET      = $2000
MEMPTR       = $18              ; $d018: screen $0400, charset $2000
DATA_START   = $3000
DATA_END     = $8000            ; no VIC bank above: data must stay below $8000

; ---- layout --------------------------------------------------------------------
LOGO_ROW     = 1
LOGO_COL     = 2                ; (40 - CELLS_W*2) / 2
TITLE_ROW    = 23
SCROLL_ROW   = 24
SCROLL_ADDR  = SCREEN + SCROLL_ROW*40

; ---- raster lines ------------------------------------------------------------
BAR_LINE     = $10              ; stable bars start at BAR_LINE+2, in the top border
BAR_COUNT    = 32
SPLIT_LINE   = $f0              ; just above the scroller row (row 24 starts at $f3)
BOTTOM_LINE  = $fc              ; below the last text row

; ---- zero page (the intro plays no music, $f0-$ff stay free) -----------------
zp_cell      = $20              ; 2 bytes: current cell record
zp_scroll    = $22              ; 2 bytes: scroll text pointer
zp_tmp       = $24              ; 2 bytes: stable pointer to a record
zp_addr      = $26              ; 2 bytes: where the current cell is written

; ---- cell record layout (ces_cells: 10 bytes) --------------------------------
C_X          = 0
C_Y          = 1
C_TL         = 2                ; the four chars in place ...
C_TR         = 3
C_BL         = 4
C_BR         = 5
C_TL1        = 6                ; ... and their "one char lower" codes
C_TR1        = 7
C_BL1        = 8
C_BR1        = 9
CELL_SIZE    = 10

; =============================================================================
        +basic_upstart

start:
        +demo_init nmi
        lda #BLACK
        sta BORDER
        sta BACKGROUND
        lda #MEMPTR
        sta VIC_MEMPTR
        lda #$c8                ; 40 columns, no fine scroll
        sta VIC_CTRL2
        lda #$20                ; clear screen and colour RAM
        +fill_1000 SCREEN
        lda #BLACK
        +fill_1000 COLOR_RAM
        jsr copy_chars          ; IRQs are still off: banks the I/O out
        jsr draw_title
        jsr scroller_init
        lda #0
        sta intro_frame
        jsr draw_all            ; first frame: every cell in place
        lda #WHITE              ; DEBUG: colour map visibility
        +fill_1000 COLOR_RAM

        lda #$1b                ; DEN on, 25 rows, yscroll 3, raster MSB 0
        sta VIC_CTRL1
        +set_irq irq_bars1, BAR_LINE
        lda #$01
        sta VIC_IRQ_ENABLE
        sta VIC_IRQ_STATUS
        cli

; ---- main loop: once per frame, after irq_bottom ------------------------------
main_loop:
        lda frame_flag
        beq main_loop
        lda #0
        sta frame_flag
        jsr rotate_bars
        jsr scroller_update     ; must run between $fc and $f0 (it does)
        jsr wave_update
        jmp main_loop

nmi:    rti

; =============================================================================
; IRQ handlers
; =============================================================================

; ---- split: fine scroll for the scroller row ---------------------------------
irq_split:
        +irq_enter
        lda scroll_x            ; bit3=0 -> 38 columns, hides the edge chars
        sta VIC_CTRL2
        +set_irq irq_bottom, BOTTOM_LINE
        +irq_exit

; ---- bottom: restore the screen, signal the main loop ------------------------
irq_bottom:
        +irq_enter
        lda #$c8
        sta VIC_CTRL2
        inc frame_flag
        +set_irq irq_bars1, BAR_LINE
        +irq_exit

; ---- stable raster bars (double IRQ), must not cross a page ------------------
        !align 255, 0
irq_bars1:
        sta save_a
        stx save_x
        sty save_y
        lda #<irq_bars2
        sta IRQ_VECTOR
        lda #>irq_bars2
        sta IRQ_VECTOR+1
        inc VIC_RASTER
        asl VIC_IRQ_STATUS
        tsx
        cli
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
        nop
irq_bars2:
        txs
        ldx #$08
-       dex
        bne -
        bit $00
        lda VIC_RASTER
        cmp VIC_RASTER
        beq +
+       ldx #0                  ; ---- cycle exact from here, 63 cycles/line
.bar:   lda bars,x              ; 4
        sta BORDER              ; 4
        ldy #9                  ; 2
-       dey                     ; 44
        bne -
        nop                     ; 2
        inx                     ; 2
        cpx #BAR_COUNT          ; 2
        bne .bar                ; 3  = 63
        lda #BLACK
        sta BORDER

        lda #<irq_split
        sta IRQ_VECTOR
        lda #>irq_split
        sta IRQ_VECTOR+1
        lda #SPLIT_LINE
        sta VIC_RASTER
        asl VIC_IRQ_STATUS
        lda save_a
        ldx save_x
        ldy save_y
        rti

save_a: !byte 0
save_x: !byte 0
save_y: !byte 0

; =============================================================================
; Helpers
; =============================================================================

; ces_chars -> charset, codes CES_FIRST.. ; codes 0..CES_FIRST-1 stay blank
; ($00 is the logo's background and $01 is never used, so two codes are free)
; (the intro has no text in the custom charset: rows 23-24 use the ROM font,
; and rows 0-22 are cleared). IRQs are off, so bank the I/O out and copy.
copy_chars:
        lda #BANK_ALL_RAM
        sta CPU_PORT
        lda #0
        ldx #0
-       sta CHARSET,x
        sta CHARSET+$100,x
        sta CHARSET+$200,x
        sta CHARSET+$300,x
        sta CHARSET+$400,x
        sta CHARSET+$500,x
        sta CHARSET+$600,x
        sta CHARSET+$700,x
        inx
        bne -
        lda #<(ces_chars - CES_FIRST*8)   ; data page n goes to CHARSET + CES_FIRST*8 + n*$100
        sta zp_tmp
        lda #>(ces_chars - CES_FIRST*8)
        sta zp_tmp+1
        ldx #0                  ; page inside the charset ($2000 + x*$100)
.page:  ldy #0
-       lda (zp_tmp),y
        sta CHARSET,x
        inc zp_tmp
        bne +
        inc zp_tmp+1
+       iny
        bne -
        txa
        clc
        adc #>((CHARSET + CES_FIRST*8) / $100 & $ff)     ; charset page = base + n
        sta zp_tmp
        inx
        cpx #(CES_CHARS*16 + $ff) / $100
        bne .page
        lda #BANK_IO_ONLY
        sta CPU_PORT
        rts

draw_title:
        ldx #0
-       lda title,x
        beq +
        sta SCREEN+TITLE_ROW*40+(40-TITLE_LEN)/2,x
        lda #YELLOW
        sta COLOR_RAM+TITLE_ROW*40+(40-TITLE_LEN)/2,x
        inx
        bne -
+       rts

; zp_addr = SCREEN + y2*40 + x2 (y2 already includes LOGO_ROW)
cell_addr:
        lda #SCREEN & $ff
        clc
        adc x2
        sta zp_addr
        lda #(SCREEN / $100) & $ff
        adc #0
        sta zp_addr+1
        ldx #0
-       lda zp_addr
        clc
        adc #40
        sta zp_addr
        bcc +
        inc zp_addr+1
+       inx
        cpx y2
        bne -
        rts

; ces_cells -> screen: every cell in place (frame 0).
draw_all:
        lda #<ces_cells
        sta zp_cell
        lda #>ces_cells
        sta zp_cell+1
        ldx #0
-       ldy #C_Y
        lda (zp_cell),y
        clc
        adc #LOGO_ROW
        sta y2
        ldy #C_X
        lda (zp_cell),y
        sta x2
        lda zp_cell
        sta zp_tmp
        lda zp_cell+1
        sta zp_tmp+1
        jsr cell_addr
        ldy #C_TL
-       lda (zp_tmp),y
        sta (zp_addr),y
        iny
        cpy #C_TL+4
        bne -
        lda zp_cell
        clc
        adc #CELL_SIZE
        sta zp_cell
        bcc +
        inc zp_cell+1
+       inx
        cpx #CELL_COUNT
        bne -
        rts

; ---- scroller -------------------------------------------------------------------
scroller_init:
        lda #<scroll_text
        sta zp_scroll
        lda #>scroll_text
        sta zp_scroll+1
        ldx #39
        lda #LIGHT_GREEN
-       sta COLOR_RAM+SCROLL_ROW*40,x
        dex
        bpl -
        rts

scroller_update:
        lda scroll_x
        sec
        sbc #1
        and #$07
        sta scroll_x
        bcs .sdone
        ldx #0
-       lda SCROLL_ADDR+1,x
        sta SCROLL_ADDR,x
        inx
        cpx #39
        bne -
        ldy #0
        lda (zp_scroll),y
        bne +
        lda #<scroll_text
        sta zp_scroll
        lda #>scroll_text
        sta zp_scroll+1
        lda (zp_scroll),y
+       sta SCROLL_ADDR+39
        inc zp_scroll
        bne .sdone
        inc zp_scroll+1
.sdone: rts

; =============================================================================
; Effects
; =============================================================================

rotate_bars:                    ; bars[x] = bars[x+1], bars[31] = old bars[0]
        lda bars
        pha
        ldx #0
-       lda bars+1,x
        sta bars,x
        inx
        cpx #BAR_COUNT-1
        bne -
        pla
        sta bars+BAR_COUNT-1
        rts

; ---- the chase ------------------------------------------------------------------
; Cell c has phase p = (frame + ces_cell_wave[c]) & 15:
;   p < HIDDEN          in place        drawn at (x, y),       codes TL..BR
;   p < HIDDEN + 5      one char lower  drawn at (x, y + 1),   codes TL1..BR1
;   else                hidden above    drawn at (x, y - 2),   codes TL1..BR1
; (a "lower" code shows the low half of its char on the char above, so a sliding
; cell stretches up by one char row: the chase). The phase changes every frame,
; but only when it crosses HIDDEN (cell starts moving) or HIDDEN + 5 (cell stops)
; does anything need redrawing: the cell and its four neighbours. The vertical
; edges of adjacent cells are aligned, so the 2x2 grid just meets.
wave_update:
        inc intro_frame
        ldx #CELL_COUNT-1
.cell:  lda intro_frame
        clc
        adc ces_cell_wave,x
        and #$0f
        cmp #HIDDEN
        beq .dirty
        cmp #HIDDEN + 5
        beq .dirty
.next:  dex
        bpl .cell
        rts
.dirty: stx cell_no
        jsr draw_one            ; the cell itself
        cpx #CELLS_W            ; and its four neighbours, when they exist
        bcc .no_up
        stx cell_no
        txa
        sbc #CELLS_W-1          ; x - CELLS_W (carry set by cpx)
        jsr draw_one
.no_up: ldx cell_no
        cpx #CELL_COUNT-CELLS_W
        bcs .no_down
        stx cell_no
        txa
        adc #CELLS_W-1          ; x + CELLS_W (carry clear: cpx did not reach)
        jsr draw_one
.no_down:
        ldx cell_no
        txa
        and #CELLS_W-1
        beq .no_left
        stx cell_no
        txa
        sec
        sbc #0                  ; x - 1
        jsr draw_one
.no_left:
        ldx cell_no
        txa
        and #CELLS_W-1
        cmp #CELLS_W-1
        beq .no_right
        stx cell_no
        txa
        clc
        adc #1                  ; x + 1
        jsr draw_one
.no_right:
        ldx cell_no
        jmp .next

; =============================================================================
; ---- one cell: read it, work out where it goes this frame, draw it -----------
; A = cell index (preserved), zp_addr points just after the record on return.
draw_one:
        tax
        lda #0
        sta zp_tmp
        txa                     ; record = ces_cells + index*10 = ((x*5)*2)
        asl
        rol zp_tmp
        clc
        adc #<ces_cells         ; x*2
        sta zp_cell
        lda zp_tmp
        adc #>ces_cells
        sta zp_cell+1
        lda zp_cell             ; *4
        asl
        sta zp_cell
        lda zp_cell+1
        rol
        sta zp_cell+1
        asl zp_cell             ; *8
        rol zp_cell+1
        lda zp_cell             ; *2 again, added: *8 + *2 = *10
        clc
        adc #<ces_cells
        sta zp_cell
        lda zp_cell+1
        adc #>ces_cells
        sta zp_cell+1
        ldy #C_Y
        lda (zp_cell),y         ; y in the logo (0, 2, ...)
        clc
        adc #LOGO_ROW
        sta y2
        ldy #C_X
        lda (zp_cell),y
        sta x2
        lda zp_cell             ; zp_tmp = the record (stable while the address
        sta zp_tmp              ;  maths use zp_addr)
        lda zp_cell+1
        sta zp_tmp+1
        txa                     ; phase = (frame + wave[index]) & 15
        tay
        lda intro_frame
        clc
        adc ces_cell_wave,y
        and #$0f
        cmp #HIDDEN
        bcc .place              ; in place:  (x, y),     codes TL..BR
        cmp #HIDDEN + 5
        bcc .lower              ; sliding:   (x, y + 1), codes TL1..BR1
        lda y2                  ; hidden:    (x, y - 2), codes TL1..BR1
        sec
        sbc #3
        sta y2
.lower: inc y2
        jsr cell_addr
        ldy #C_TL1
        bne .copy               ; always taken (TL1 != 0)
.place: jsr cell_addr
        ldy #C_TL
.copy:  lda (zp_tmp),y
        sta (zp_addr),y
        iny
        cpy #C_TL+4
        bne .copy
        txa
        tax
        rts

; =============================================================================
!if * > CODE_END { !error "code reaches $1000: move data after DATA_START" }

        * = DATA_START

        !source "src/gfx/ces_intro.asm"     ; ces_chars, ces_cells, ces_cell_wave

frame_flag:   !byte 0
intro_frame:  !byte 0
scroll_x:     !byte 7
cell_no:      !byte 0           ; index of the cell the chase is redrawing
x2:           !byte 0           ; column of the top-left char of a cell
y2:           !byte 0           ; and its screen row

bars:   ; 32 lines, rotated every frame. Page aligned: lda bars,x never crosses
        !byte $06,$0e,$03,$01,$03,$0e,$06,$00
        !byte $00,$00,$00,$00,$00,$00,$00,$00
        !byte $09,$08,$0a,$07,$01,$07,$0a,$08
        !byte $09,$00,$00,$00,$00,$00,$00,$00

title:
        !scr "codeurs en seine 2026"
TITLE_LEN = * - title
        !byte 0

scroll_text:
        !scr "      *** codeurs en seine 2026 ***    kindarena, rouen, 19.11.2026 ...    wave, codeurs!    see you in the auditorium!          "
        !byte 0

!if * > DATA_END { !error "data reaches $8000 (no VIC bank there)" }
