#!/usr/bin/env python3
"""Regenerate the Codeurs en Seine logo data, used by both demos.

src/gfx/ces_logo.*  (tools/img2chars.py): the logo at 176 px, one font pixel = one
                    char, used by src/main.asm (part "ces").
src/gfx/ces_intro.* (this file): the same logo at 2x, cut into 2x2-char cells with
                    the characters a vertical chase needs, used by src/intro.asm.

Usage: python3 tools/ces_intro.py     (needs rsvg-convert, like `make gfx`)
"""
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import img2chars as i2c                                      # noqa: E402

GFX = os.path.join(ROOT, "src", "gfx")
SVG = os.path.join(ROOT, "assets", "codeurs-en-seine-logo.svg")
WIDTH = 352                     # 2x the 176 px logo
PERIOD = 16                     # intro frames per chase step (2 chars down + 2 up)
HIDDEN = 10                     # first phase of the 6 "hidden above" phases

png = os.path.join(tempfile.mkdtemp(), "logo.png")
subprocess.run(["rsvg-convert", "-w", str(WIDTH), "-b", "black", "-o", png, SVG], check=True)
bm = i2c.crop(i2c.load_png(png))
PH, PW = len(bm), len(bm[0])
CW, CH = PW // 16, PH // 16


def strip(x0, y0):
    """8 source lines of the 8x16 char whose top-left is (x0, y0); blank outside."""
    rows = []
    for y in range(8):
        b = 0
        for x in range(8):
            if 0 <= x0 + x < PW and 0 <= y0 + y < PH and bm[y0 + y][x0 + x]:
                b |= 0x80 >> x
        rows.append(b)
    return tuple(rows)


BLANK = 0x02                    # $00 = logo background, $01 free: two blank chars
codes, charset = {}, []


def code_for(s, last):
    """Code of an 8x16 char: strip s on the top half, or on the bottom half (last)."""
    key = (s, last)
    if key not in codes:
        codes[key] = BLANK + len(codes)
        charset.append(list(s) + [0] * 8 if last else list(s) + [0] * 8)
    return codes[key]


cells = []
for cy in range(CH):
    for cx in range(CW):
        four = []
        for r in (0, 1):
            for c in (0, 1):
                if r == 1:
                    # the cell's own lower char row
                    s = strip(cx * 16 + c * 8, cy * 16 + 8)
                elif cy > 0:
                    # the strip one char below, whose ink is in its lower half:
                    # shifted up 8 px it fills this cell's upper row, and the
                    # cell above draws the very same line. So a cell only owns
                    # two strips (row 0 borrows from row 1 of the cell above).
                    s = tuple(a >> 8 for a in strip(cx * 16 + c * 8, cy * 16))
                    four.append((code_for(s, False), code_for(s, True)))
                    continue
                else:
                    s = strip(cx * 16 + c * 8, 0)
                # the top row of the logo only travels down, so "shown lower" is
                # never used there: one char, and 0 in the slot
                four.append((code_for(s, False), 0 if cy == 0 else code_for(s, True)))
        cells.append((cx, cy, four))

if len(charset) > 256 - BLANK:
    raise SystemExit(f"{len(charset)} chars needed, only {256 - BLANK} codes")

hdr = ("; generated by tools/ces_intro.py from assets/codeurs-en-seine-logo.svg "
       "- do not edit\n")
with open(os.path.join(GFX, "ces_intro.asm"), "w") as f:
    f.write(hdr)
    f.write(f"ces_chars:  ; codes ${BLANK:02x}-${BLANK + len(charset) - 1:02x}, 16 bytes each\n")
    for i, data in enumerate(charset):
        f.write("        !byte " + ",".join(f"${v:02x}" for v in data) + f"  ; ${BLANK + i:02x}\n")
    f.write("ces_cells:  ; x, y, then four (shown in place, shown lower) code pairs\n")
    for (cx, cy, four) in cells:
        f.write("        !byte %2d,%2d, " % (cx * 2, cy * 2))
        f.write(",".join(f"${a:02x},${b:02x}" for a, b in four) + "\n")
    # chase offsets: a diagonal (c + cx) wave plus a row delay (cy), steps of 2
    wave = [(2 * c + 2 * (c % CW) + 2 * (c // CW)) % PERIOD for c in range(len(cells))]
    f.write("ces_cell_wave:  ; added to the intro frame to get each cell's phase\n")
    f.write("        !byte " + ",".join(str(v) for v in wave) + "\n")

with open(os.path.join(GFX, "ces_intro.inc.asm"), "w") as f:
    f.write(hdr)
    f.write(f"CELLS_W = {CW}\nCELLS_H = {CH}\nCELL_COUNT = {len(cells)}\n")
    f.write(f"CES_FIRST = ${BLANK:02x}\nCES_CHARS = {len(charset)}\nPERIOD = {PERIOD}\nHIDDEN = {HIDDEN}\n")

print(f"{CW}x{CH} cells ({len(cells)}), {len(charset)} chars")
