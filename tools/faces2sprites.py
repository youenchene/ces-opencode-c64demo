#!/usr/bin/env python3
"""Generate 16 in-plane spin poses per portrait as four C64 sprites per pose."""
import math
from pathlib import Path

from img2chars import load_png

ROOT = Path(__file__).resolve().parents[1]
PORTRAITS = ("etienne-reith", "yann-petit")


def poses(image):
    """Fit the cutout into a spinning disc centred on the 48x42 sprite grid."""
    lit = [(x, y) for y, row in enumerate(image) for x, value in enumerate(row)
           if value >= 75]
    cx = (min(x for x, _ in lit) + max(x for x, _ in lit)) / 2
    cy = (min(y for _, y in lit) + max(y for _, y in lit)) / 2
    scale = max(math.hypot(x - cx, y - cy) for x, y in lit) / 20
    thresholds = ((92, 148), (176, 120))
    for frame in range(16):
        angle = math.tau * frame / 16
        c, s = math.cos(angle), math.sin(angle)
        grid = []
        for y in range(42):
            row = []
            for x in range(48):
                dx, dy = x - 23.5, y - 20.5
                sx = round(cx + scale * (c * dx + s * dy))
                sy = round(cy + scale * (-s * dx + c * dy))
                row.append(0 <= sy < len(image) and 0 <= sx < len(image[sy])
                           and image[sy][sx] >= thresholds[sy % 2][sx % 2])
            grid.append(row)
        yield grid


def sprite_rows(grid, x0, y0):
    for row in grid[y0:y0 + 21]:
        yield [sum(row[x + bit] << (7 - bit) for bit in range(8))
               for x in range(x0, x0 + 24, 8)]
    yield [0]  # pad the sprite to 64 bytes


def main():
    with (ROOT / "src/gfx/heads.sprites.asm").open("w") as output:
        print("; generated by tools/faces2sprites.py - do not edit (see `make gfx`)", file=output)
        for i, name in enumerate(PORTRAITS):
            print(f"head{i}_sprites:", file=output)
            image = load_png(ROOT / f"assets/organisers/{name}-face.png")
            for frame, grid in enumerate(poses(image)):
                print(f"; {name}, pose {frame}", file=output)
                for x, y in ((0, 0), (24, 0), (0, 21), (24, 21)):
                    for data in sprite_rows(grid, x, y):
                        print("        !byte " + ",".join(f"${byte:02x}" for byte in data),
                              file=output)


if __name__ == "__main__":
    main()
